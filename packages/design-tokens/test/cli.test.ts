test("usage errors: exit 2, a code, a message and a fix", async () => {
  const cases: [string[], string][] = [
    [["bild"], "unknown-command"],
    [["build", "--chek"], "unknown-option"],
    [["build", "--theme"], "missing-value"],
    [["build", "--theme", "nope"], "theme-not-found"],
    [["build", "--theme", "nope.json"], "theme-not-found"],
    [["build", "--check=1"], "unexpected-value"],
    [["build", "--out", "a", "--out", "b"], "repeated-option"],
  ];
  for (const [argv, code] of cases) {
    const result = await cli(...argv, "--json");
    assert.equal(result.code, EXIT.usage, argv.join(" "));
    assert.deepEqual([result.json.ok, result.json.exitCode, result.json.error.code], [false, 2, code], argv.join(" "));
    assert.ok(result.json.error.message && result.json.error.fix, argv.join(" "));
  }
  assert.match((await cli("bild")).stderr, /Did you mean `by-tokens build`/);
  assert.match((await cli("build", "--chek", "--json")).json.error.fix, /--check/);

  const garbled = join(scratch, "garbled.theme.json");
  writeFileSync(garbled, "{ not json");
  assert.equal((await cli("validate", "--theme", garbled, "--json")).json.error.code, "theme-invalid-json");
});

