test("the installed binary runs, prints one JSON document and sets the exit code", () => {
  const bin = join(ROOT, "bin", "by-tokens.js");
  assert.ok(existsSync(join(ROOT, "dist", "cli", "main.js")), "dist is missing: run `pnpm --filter @byterygon/design-tokens build` before the tests");
  const ok = JSON.parse(execFileSync(process.execPath, [bin, "build", "--check", "--json"], { cwd: scratch, encoding: "utf8" }));
  assert.deepEqual([ok.command, ok.ok, ok.theme], ["build", true, "default"]);
  const failed = spawnSync(process.execPath, [bin, "explain", "nope", "--json"], { cwd: scratch, encoding: "utf8" });
  assert.equal(failed.status, 2);
  assert.equal(JSON.parse(failed.stdout).error.code, "unknown-token");
  assert.equal(failed.stderr, "");
});
