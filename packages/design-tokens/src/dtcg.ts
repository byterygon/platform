/**
 * The token set as a DTCG document (Design Tokens Format Module 2025.10): nested groups, `$type`,
 * `$value`, `$description`, and Byterygon metadata under `$extensions["com.byterygon"]`.
 *
 * `$value` is the value in the theme's default modes, so a tool that knows nothing about modes
 * still reads the default look. The values of every mode are under the extension's `modes`.
 */
import { type ModeContext, type Token, type TokenSet, type TokenValue, EXTENSION } from "./model.js";
import { defaultContext, valueIn } from "./resolve.js";

export interface DtcgToken {
  readonly $type: string;
  readonly $value: TokenValue;
  readonly $description: string;
  readonly $extensions: Readonly<Record<string, Readonly<Record<string, unknown>>>>;
}

export type DtcgGroup = { [key: string]: DtcgGroup | DtcgToken | unknown };

function metadata(token: Token): Record<string, unknown> {
  return {
    tier: token.tier,
    ...(token.axis && token.modes ? { axis: token.axis, modes: token.modes } : {}),
    ...(token.tailwind ? { tailwind: token.tailwind } : {}),
    ...(token.ramp ? { ramp: token.ramp } : {}),
    ...(token.overridden ? { overridden: true } : {}),
  };
}

/** A nested tree of the tokens with their own values in `context` (aliases kept as written). */
export function tokenTree(set: TokenSet, context: ModeContext): DtcgGroup {
  const root: DtcgGroup = {};
  for (const token of set.tokens.values()) {
    const segments = token.path.split(".");
    let group = root;
    for (const segment of segments.slice(0, -1)) {
      group[segment] ??= {};
      group = group[segment] as DtcgGroup;
    }
    const value = valueIn(token, context);
    if (value === undefined) continue;
    const node: DtcgToken = {
      $type: token.type,
      $value: value,
      $description: token.description,
      $extensions: { [EXTENSION]: metadata(token) },
    };
    group[segments[segments.length - 1]!] = node;
  }
  return root;
}

/** The complete DTCG document for a theme. */
export function toDtcg(set: TokenSet): DtcgGroup {
  return {
    $description: `Byterygon design tokens, theme "${set.name}". Generated by by-tokens; edit the theme file or the catalogue, not this file.`,
    $extensions: {
      [EXTENSION]: {
        theme: set.name,
        format: "Design Tokens Format Module 2025.10",
        axes: set.axes.map((axis) => ({ name: axis.name, attribute: axis.attribute, modes: axis.modes, default: axis.default })),
        contrast: set.contrast,
      },
    },
    ...tokenTree(set, defaultContext(set)),
  };
}
