// Export experimental clients solely from the Rust-derived, agreement-checked graph.
import { readFileSync, writeFileSync as writeRaw } from "node:fs";
import { format } from "prettier";
async function writeFileSync(path, source) {
  writeRaw(
    path,
    path.pathname.endsWith(".rs")
      ? source
      : await format(source, {
          parser: path.pathname.endsWith(".ts") ? "typescript" : "babel",
        }),
  );
}
const result = JSON.parse(
  readFileSync(new URL("../results/fingerprints.json", import.meta.url)),
);
const input = result.model.input;
await writeFileSync(
  new URL("./generated.mjs", import.meta.url),
  `// Generated by export.mjs from the checked Rust semantic model.\nimport {descriptor} from './descriptor.mjs';\nexport const CONTRACT=${JSON.stringify(result.contract)};\nexport const POLICY=${JSON.stringify(result.policy)};\nexport const CONTRACT_CHECKED=${JSON.stringify(result.contractProfiles.checked)};\nexport const document=${JSON.stringify(input)};\nexport const schema=descriptor(document);\n`,
);
let names = Object.keys(input.definitions).sort();
function emit(node, profile) {
  if (node.mapping === "checked-number" && profile.includes("Checked"))
    return "number";
  if (node.ref)
    return `${profile}_${names.findIndex((name) => name === node.ref + ".Input" || name === node.ref + ".Output")}`;
  switch (node.type) {
    case "i64":
      return profile.includes("Bigint") ? "bigint" : "ExactI64";
    case "u64":
      return profile.includes("Bigint") ? "bigint" : "ExactU64";
    case "i8":
    case "i16":
    case "i32":
    case "u8":
    case "u16":
    case "u32":
      return "number";
    case "string":
      return "string";
    case "bool":
      return "boolean";
    case "bytes":
      return "Uint8Array";
    case "decimal":
      return "AmbidexDecimal";
    case "instant":
    case "date":
    case "local":
    case "time":
    case "duration":
      return "AmbidexTemporal";
    case "unit":
      return "null";
    case "nullable":
      return `(${emit(node.inner, profile)} | null)`;
    case "dynamic":
      return "unknown";
    case "array":
      return `Array<${emit(node.items, profile)}>`;
    case "map":
      return `Record<string, ${emit(node.values, profile)}>`;
    case "tuple":
      return `[${node.items.map((n) => emit(n, profile)).join(", ")}]`;
    case "object": {
      const normal = node.fields.filter((f) => !f.flatten),
        flat = node.fields.filter((f) => f.flatten);
      return [
        "{ " +
          normal
            .map(
              (f) =>
                JSON.stringify(f.name) +
                (f.optional ? "?" : "") +
                ": " +
                emit(f.schema, profile),
            )
            .join("; ") +
          " }",
        ...flat.map((f) => emit(f.schema, profile)),
      ].join(" & ");
    }
    case "enum":
      return node.variants
        .map((v) => {
          const type = emit(v.schema, profile);
          if (node.untagged) return type;
          if (node.tag)
            return node.content
              ? `{ ${JSON.stringify(node.tag)}: ${JSON.stringify(v.name)}; ${JSON.stringify(node.content)}: ${type} }`
              : `({ ${JSON.stringify(node.tag)}: ${JSON.stringify(v.name)} } & ${type})`;
          return v.schema.type === "unit"
            ? JSON.stringify(v.name)
            : `{ ${JSON.stringify(v.name)}: ${type} }`;
        })
        .join(" | ");
    default:
      throw new Error("unsupported semantic type " + node.type);
  }
}
let out = `// Generated from Rust semantic declarations; no handwritten field list.\nimport type {AmbidexDecimal, AmbidexTemporal} from './semantic.mjs';\nexport type ExactI64 = bigint & {readonly __exactI64: unique symbol};\nexport type ExactU64 = bigint & {readonly __exactU64: unique symbol};\n`;
for (const profile of ["Bigint", "Checked"]) {
  names.forEach((name, i) => {
    out += `type ${profile}_${i} = ${emit(input.definitions[name], profile)};\n`;
  });
  out += `export type ${profile}Input = ${emit(input.root, profile)};\n`;
}
names = Object.keys(result.mappingExample.definitions).sort();
for (const profile of ["MappingBigint", "MappingChecked"]) {
  names.forEach((name, i) => {
    out += `type ${profile}_${i} = ${emit(result.mappingExample.definitions[name], profile)};\n`;
  });
  out += `export type ${profile}Input = ${emit(result.mappingExample.root, profile)};\n`;
}
names = Object.keys(result.model.error.definitions).sort();
// The same nominal emitter handles the error's output-direction references.
for (const profile of ["BigintError", "CheckedError"]) {
  names.forEach((name, i) => {
    out += `type ${profile}_${i} = ${emit(result.model.error.definitions[name], profile)};\n`;
  });
  out += `export type ${profile} = ${emit(result.model.error.root, profile)};\n`;
}
await writeFileSync(new URL("./generated.d.ts", import.meta.url), out);
await writeFileSync(
  new URL("./workloads.mjs", import.meta.url),
  `// Generated from Rust scenario declarations.\nimport {descriptor} from './descriptor.mjs';\nimport {decodeTyped} from './semantic.mjs';\nimport {jsonBytes} from './codec.mjs';\nconst source=${JSON.stringify(result.workloads)};
for(const[count,name]of [[32,'large-control-256KiB'],[64,'large-control-512KiB'],[127,'large-control-near-1MiB']])source.push({name,supplemental:true,schema:${JSON.stringify(result.largeControlSchema)},json:Array(count).fill('x'.repeat(8190)),legacy:Array(count).fill('x'.repeat(8190))});\nexport const workloads=source.map(w=>({...w,schema:descriptor(w.schema),value:decodeTyped(jsonBytes(w.json),descriptor(w.schema),'json')}));\n`,
);

await writeFileSync(
  new URL("../rust/src/generated_ids.rs", import.meta.url),
  `// Generated from Rust semantic declarations; run fingerprint then ts/export.mjs.\npub const CONTRACT: &str =\n    ${JSON.stringify(result.contract)};\npub const POLICY: &str = ${JSON.stringify(result.policy)};\n`,
);
