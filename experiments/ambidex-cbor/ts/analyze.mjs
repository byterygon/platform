import { readFileSync, writeFileSync } from "node:fs";
const load = (name) =>
  JSON.parse(readFileSync(new URL("../results/" + name, import.meta.url)));
const summary = load("summary.json"),
  rust = load("rust-bench.json"),
  node = load("node-bench.json"),
  browser = load("browser-bench.json"),
  bundle = load("bundle.json");
const primary = [
  "ExecuteSummary",
  "metadata-500",
  "mutation-20",
  "edited-grid",
];
if (
  node.results.length !== 210 ||
  rust.results.length !== 105 ||
  browser.results.length !== 2 ||
  browser.results.some((r) => r.error || r.raw?.length !== 315) ||
  load("transport-bench.json").results.length !== 210
)
  throw new Error("Incomplete benchmark campaign");
function pair(rows, stage, name) {
  return ["json", "cbor"].map((c) =>
    rows.find((r) => r.key.endsWith("/" + stage + "/" + name + "/" + c)),
  );
}
const pct = (a, b) => (a > 0 ? ((a - b) / a) * 100 : null);
const matches = primary.filter((name) =>
  summary.browsers.every((engine) => {
    const [a, b] = pair(engine.summary, "websocket-rpc", name);
    return a && b && pct(a.p95Ms, b.p95Ms) >= 15;
  }),
);
const metrics = {
  sharedBrowserWorkflowsWithAtLeast15PercentObservedP95Gain: matches,
  latencyGainGateObserved: matches.length >= 2,
  heapGate:
    "not established: WebKit exposes neither heap nor GC; Chromium heap is sampled/nonstandard",
  incrementalExperimentalGzipBytes: bundle.incrementalGzipBytes,
  bundleGateObserved: bundle.incrementalGzipBytes <= 30720,
  cborDecision: "No-Go for production adoption",
};
const fmt = (n) => (n === null ? "unresolved" : n.toFixed(4));
let text =
  "# Measured results\n\nGenerated by `node ts/analyze.mjs` from the committed raw data. Positive gain means CBOR is faster. Browser codec/mock timings average batches; WebSocket timings are individual round trips. JSON here means lossless JSON v2; JSON-v1 is contextual in raw data.\n\n";
text +=
  "## Four primary workflows: codec p95\n\n| Engine | Workload | JSON ms | CBOR ms | CBOR gain | JSON / CBOR bytes |\n| --- | --- | ---: | ---: | ---: | ---: |\n";
for (const [engine, rows] of [
  ["Node", summary.node],
  ["Rust", summary.rust],
  ...summary.browsers.map((r) => [r.engine, r.summary]),
])
  for (const name of primary) {
    const [a, b] = pair(rows, "codec", name);
    text += `| ${engine} | ${name} | ${fmt(a.p95Ms)} | ${fmt(b.p95Ms)} | ${fmt(pct(a.p95Ms, b.p95Ms))}% | ${a.bytes} / ${b.bytes} |\n`;
  }
text +=
  "\n## Browser WebSocket loopback RPC p95\n\n| Engine | Workload | JSON ms | CBOR ms | CBOR gain |\n| --- | --- | ---: | ---: | ---: |\n";
for (const engine of summary.browsers)
  for (const name of primary) {
    const [a, b] = pair(engine.summary, "websocket-rpc", name);
    text += `| ${engine.engine} | ${name} | ${fmt(a.p95Ms)} | ${fmt(b.p95Ms)} | ${fmt(pct(a.p95Ms, b.p95Ms))}% |\n`;
  }
text += `\nShared workflows meeting the observed ≥15% gain in both browsers: **${matches.length}** (${matches.join(", ") || "none"}). The latency gate is ${metrics.latencyGainGateObserved ? "met by these point estimates" : "not established"}. WebKit timer quantization and the exploratory confidence intervals limit interpretation; no heap gate can be certified. This is not real Tauri WKWebView, TLS, or a production authenticated RPC benchmark.\n`;
text +=
  "\n## Rust requested-byte allocations and CPU\n\n| Workload | Codec | Allocations / op | Peak requested live bytes above baseline | User CPU μs / op |\n| --- | --- | ---: | ---: | ---: |\n";
for (const name of primary)
  for (const codec of ["json", "cbor"]) {
    const rows = rust.results.filter(
        (r) => r.name === name && r.codec === codec,
      ),
      count = rows.reduce((n, r) => n + r.samplesMs.length, 0);
    text += `| ${name} | ${codec} | ${fmt(rows.reduce((n, r) => n + r.allocationCalls, 0) / count)} | ${Math.max(...rows.map((r) => r.peakRequestedLiveBytesAboveBaseline))} | ${fmt((rows.reduce((n, r) => n + r.cpuUserSeconds, 0) * 1e6) / count)} |\n`;
  }
text +=
  "\nSystem allocator instrumentation counts requested bytes and calls; it does not include allocator overhead. Process peak RSS is cumulative and stored separately in the raw Rust rows. Node rows contain sampled heap/RSS, CPU and perf_hooks GC events; transient peaks can be missed. Browser memory limitations are recorded per engine.\n";
text +=
  "\n## Direct serde versus logical tree\n\n| Path | p95 ms | Allocations / op |\n| --- | ---: | ---: |\n";
for (const mode of ["direct-serde", "logical-tree"]) {
  const rows = rust.directVsTree.filter((r) => r.mode === mode),
    a = rows.flatMap((r) => r.samplesMs).sort((a, b) => a - b);
  text += `| ${mode} | ${fmt(a[Math.floor((a.length - 1) * 0.95)])} | ${fmt(rows.reduce((n, r) => n + r.allocationCalls, 0) / a.length)} |\n`;
}
text +=
  "\nThis microbenchmark compares validated parsing/hydration paths, not complete approval/digest/audit integration. The direct path would still need canonical logical digest generation in a production router.\n";
text += `\n## Size and uncertainty\n\nThe experimental dual-codec build adds **${bundle.incrementalGzipBytes} gzip bytes** over a JSON-only build that explicitly removes raw CBOR implementations. This is not a production package-size promise. The standalone cbor-x comparator is ${bundle.rows.find((r) => r.name === "cborX").gzipBytes} gzip bytes.\n\nFive independent trials alternate codec order for Node/browser codec runs. Rust and the separate Node transport runs have fixed order. Summary artifacts include p50/p95, trial ranges and seeded exploratory bootstrap intervals across only five trial p95 values. No p99 claims are made. Supplemental 256 KiB, 512 KiB and near-1 MiB controls have fewer samples and are excluded from adoption gates. All benchmark programs ran sequentially in bench.sh; the host was not an isolated performance machine.\n`;
writeFileSync(new URL("../RESULTS.md", import.meta.url), text);
writeFileSync(
  new URL("../results/analysis.json", import.meta.url),
  JSON.stringify(metrics, null, 2) + "\n",
);
console.log(metrics);
