#!/usr/bin/env node
// The tools' own marks (Mightyconsole spec DOC-21, Open question 45 (e)): marks/ holds the Simple
// Icons files byte for byte with their sha256 in marks/manifest.json; this script checks them and
// writes src/tools/marks.ts, one IconDefinition per mark (24 px artwork, drawn in currentColor by
// the Icon component). Nothing is fetched. `--check` exits 3 when a file's sha256 differs from the
// manifest or the module is stale, so CI fails when either was edited by hand.
//
//   node scripts/marks.ts            # write src/tools/marks.ts
//   node scripts/marks.ts --check    # report drift, change nothing
import { createHash } from "node:crypto";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const APP = fileURLToPath(new URL("..", import.meta.url));
export const MARKS_DIR = join(APP, "marks");
export const MODULE = join(APP, "src", "tools", "marks.ts");

export interface MarkEntry {
  export: string;
  tool: string;
  title: string;
  slug: string;
  path: string;
  sha256: string;
  owner: string;
  upstream: string;
  guidelines: string;
}

export interface Manifest {
  source: { name: string; version: string; license: string; licenseFile: string; disclaimerFile: string; notice: string };
  marks: MarkEntry[];
}

export const readManifest = (): Manifest => JSON.parse(readFileSync(join(MARKS_DIR, "manifest.json"), "utf8")) as Manifest;

/** Problems with the vendored files: a missing or changed file, an unlisted SVG, a missing notice. */
export function problems(manifest: Manifest = readManifest()): string[] {
  const out: string[] = [];
  const listed = new Set<string>();
  for (const mark of manifest.marks) {
    listed.add(mark.path);
    const file = join(MARKS_DIR, mark.path);
    if (!existsSync(file)) out.push(`${mark.path}: listed in the manifest but missing`);
    else if (createHash("sha256").update(readFileSync(file)).digest("hex") !== mark.sha256) out.push(`${mark.path}: sha256 differs from the manifest; re-vendor it, never edit it`);
  }
  for (const name of readdirSync(join(MARKS_DIR, "simple-icons"))) {
    if (name.endsWith(".svg") && !listed.has(`simple-icons/${name}`)) out.push(`simple-icons/${name}: not listed in marks/manifest.json`);
  }
  for (const file of [manifest.source.licenseFile, manifest.source.disclaimerFile, manifest.source.notice]) {
    if (!existsSync(join(MARKS_DIR, file))) out.push(`${file}: missing`);
  }
  const notice = existsSync(join(MARKS_DIR, manifest.source.notice)) ? readFileSync(join(MARKS_DIR, manifest.source.notice), "utf8") : "";
  for (const mark of manifest.marks) {
    if (!notice.includes(`**${mark.title}**`)) out.push(`${manifest.source.notice}: no trademark line for ${mark.title}`);
  }
  return out;
}

/** The path data and viewBox of a Simple Icons SVG (one path, 24 x 24). */
export function artwork(svg: string): string {
  if (!/viewBox="0 0 24 24"/.test(svg)) throw new Error("a Simple Icons mark is drawn on a 24 x 24 viewBox");
  const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]!);
  if (paths.length !== 1) throw new Error(`expected one path, found ${paths.length}`);
  return paths[0]!;
}

/** The generated module. */
export function render(manifest: Manifest = readManifest()): string {
  const lines = [
    `// Generated by scripts/marks.ts from marks/ (\`pnpm --filter @byterygon/mightyconsole marks\`); do not edit.`,
    `// The tools' own marks from ${manifest.source.name} ${manifest.source.version} (artwork data ${manifest.source.license}). Each mark is a`,
    `// trademark of its owner and is used only to identify the tool; see marks/NOTICE.md. Drawn by the Icon`,
    `// component in currentColor (monochrome), at the 24 px artwork size, shapes unchanged.`,
    `import type { IconDefinition } from "@/lib/icons";`,
    ``,
  ];
  for (const mark of manifest.marks) {
    const d = artwork(readFileSync(join(MARKS_DIR, mark.path), "utf8"));
    lines.push(`/** ${mark.title}, a trademark of ${mark.owner}. Source: ${mark.upstream} */`);
    lines.push(`export const ${mark.export}: IconDefinition = {`);
    lines.push(`  name: "mark-${mark.slug}",`);
    lines.push(`  regular: { 24: [${JSON.stringify(d)}] },`);
    lines.push(`  filled: { 24: [${JSON.stringify(d)}] },`);
    lines.push(`};`);
    lines.push(``);
  }
  return lines.join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const check = process.argv.includes("--check");
  const found = problems();
  const next = render();
  const stale = !existsSync(MODULE) || readFileSync(MODULE, "utf8") !== next;
  for (const p of found) console.error(`marks: ${p}`);
  if (check) {
    if (stale) console.error("marks: src/tools/marks.ts is stale; run `pnpm --filter @byterygon/mightyconsole marks`");
    if (found.length > 0 || stale) process.exit(3);
    console.log(`marks: ${readManifest().marks.length} marks OK`);
  } else {
    if (found.length > 0) process.exit(3);
    writeFileSync(MODULE, next);
    console.log(`marks: wrote ${MODULE}`);
  }
}
