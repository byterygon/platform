CREDS = """-----BEGIN NATS USER JWT-----
{jwt}
------END NATS USER JWT------

************************* IMPORTANT *************************
NKEY Seed printed below can be used to sign and prove identity.
NKEYs are sensitive and should be treated as secrets.

-----BEGIN USER NKEY SEED-----
{seed}
------END USER NKEY SEED------

*************************************************************
"""

UNLIMITED = {"subs": -1, "data": -1, "payload": -1}


def b64url(data):
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode()


def nkey_pair(prefix):
    return nkeys.from_seed(nkeys.encode_seed(os.urandom(32), prefix))


def jwt(issuer, subject, name, nats_claims):
    """A NATS JWT (v2, ed25519-nkey) for `subject`, signed by the key pair `issuer`."""
    claims = {
        "jti": base64.b32encode(os.urandom(20)).decode().rstrip("="),
        "iat": int(datetime.datetime.now(datetime.timezone.utc).timestamp()),
        "iss": issuer.public_key.decode(),
        "name": name,
        "sub": subject,
        "nats": {**nats_claims, "version": 2},
    }
    header = b64url(json.dumps({"typ": "JWT", "alg": "ed25519-nkey"}, separators=(",", ":")).encode())
    body = b64url(json.dumps(claims, separators=(",", ":")).encode())
    signature = b64url(issuer.sign(f"{header}.{body}".encode()))
    return f"{header}.{body}.{signature}"


def operator_mode():
    """The operator, accounts and user of the JWT server: its config and the user's creds file."""
    operator = nkey_pair(nkeys.PREFIX_BYTE_OPERATOR)
    system = nkey_pair(nkeys.PREFIX_BYTE_ACCOUNT)
    account = nkey_pair(nkeys.PREFIX_BYTE_ACCOUNT)
    user = nkey_pair(nkeys.PREFIX_BYTE_USER)
    system_pub = system.public_key.decode()
    account_pub = account.public_key.decode()
    limits = {"limits": {**UNLIMITED, "imports": -1, "exports": -1, "wildcards": True, "conn": -1, "leaf": -1}}
    conf = NATS_JWT_CONF.format(
        operator=jwt(operator, operator.public_key.decode(), "lab", {"type": "operator", "system_account": system_pub}),
        system=system_pub,
        system_jwt=jwt(operator, system_pub, "SYS", {"type": "account", **limits}),
        account=account_pub,
        account_jwt=jwt(operator, account_pub, "LAB", {"type": "account", **limits}),
    )
    user_jwt = jwt(account, user.public_key.decode(), "lab-creds", {"type": "user", "pub": {}, "sub": {}, **UNLIMITED})
    return conf, CREDS.format(jwt=user_jwt, seed=user.seed.decode())


