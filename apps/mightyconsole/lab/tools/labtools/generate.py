def main(argv):
    force = "--force" in argv
    if os.path.exists(os.path.join(OUT, "credentials.json")) and not force:
        print("generate: lab/.generated is already there (use --force for new credentials)")
        return 0
    ca_key, ca_cert = ca()
    write("tls/ca.pem", ca_cert.public_bytes(serialization.Encoding.PEM))
    for name, dns in [("nats", ["localhost", "nats"]), ("kafka", ["localhost", "kafka"])]:
        key, cert = leaf(ca_key, ca_cert, name, dns, ["127.0.0.1"])
        cert_pem = cert.public_bytes(serialization.Encoding.PEM)
        write(f"tls/{name}.pem", cert_pem + ca_cert.public_bytes(serialization.Encoding.PEM))
        write(f"tls/{name}-key.pem", pem_key(key))
        if name == "kafka":
            write("tls/kafka-keystore.pem", pem_key(key) + cert_pem + ca_cert.public_bytes(serialization.Encoding.PEM))

    nats_password = secrets.token_urlsafe(18)
    seed = nkeys.from_seed(nkeys.encode_seed(os.urandom(32), nkeys.PREFIX_BYTE_USER))
    nkey_public = seed.public_key.decode()
    nkey_seed = seed.seed.decode()
    write("nats.conf", NATS_CONF.format(user="lab", password=nats_password, nkey=nkey_public))
    write("nats/lab.nk", nkey_seed + "\n", 0o600)
    write("kafka/server.properties", KAFKA_PROPERTIES)

    passphrase = secrets.token_urlsafe(12)
    plain_private, plain_public = ssh_key()
    pass_private, pass_public = ssh_key(passphrase)
    write("ssh/lab_ed25519", plain_private, 0o600)
    write("ssh/lab_ed25519.pub", plain_public + b"\n")
    write("ssh/lab_ed25519_passphrase", pass_private, 0o600)
    write("ssh/lab_ed25519_passphrase.pub", pass_public + b"\n")
    write("ssh/authorized_keys", plain_public + b"\n" + pass_public + b"\n")
    ssh_password = secrets.token_urlsafe(12)
    write("ssh/labpw.password", ssh_password + "\n")

    credentials = {
        "nats": {"url": "nats://127.0.0.1:4222", "user": "lab", "password": nats_password, "nkeySeedFile": "nats/lab.nk", "nkeyPublic": nkey_public, "caFile": "tls/ca.pem"},
        "kafka": {
            "plaintext": "127.0.0.1:9092",
            "ssl": "localhost:9093",
            "sasl": "127.0.0.1:9094",
            "scram": {"mechanism": "SCRAM-SHA-512", "user": "lab", "password": secrets.token_urlsafe(18)},
            "caFile": "tls/ca.pem",
        },
        "schemaRegistry": {"url": "http://127.0.0.1:8081"},
        "k8s": {"kubeconfigFile": "kubeconfig", "namespace": "lab"},
        "temporal": {"address": "127.0.0.1:7233", "namespaces": ["default", "lab"], "taskQueue": "lab"},
        "docker": {
            "host": "127.0.0.1",
            "port": 2222,
            "user": "lab",
            "keyFile": "ssh/lab_ed25519",
            "passphraseKeyFile": "ssh/lab_ed25519_passphrase",
            "passphrase": passphrase,
            "passwordUser": "labpw",
            "password": ssh_password,
        },
        "langgraph": {"url": "http://127.0.0.1:2024", "graph": "agent"},
    }
    write("credentials.json", json.dumps(credentials, indent=2) + "\n")
    print(f"generate: wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
