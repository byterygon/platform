def ensure_s3():
    """The S3 store of Temporal External Storage (TSK-103, SeaweedFS): a read-write identity and a
    read-only one, added to an existing credentials.json without touching the rest."""
    path = os.path.join(OUT, "credentials.json")
    with open(path) as f:
        credentials = json.load(f)
    temporal = credentials.setdefault("temporal", {})
    if "externalStorage" in temporal and os.path.exists(os.path.join(OUT, "seaweedfs/s3.json")):
        return
    writer = {"accessKeyId": "lab" + secrets.token_hex(6), "secretAccessKey": secrets.token_urlsafe(24)}
    reader = {"accessKeyId": "labro" + secrets.token_hex(6), "secretAccessKey": secrets.token_urlsafe(24)}
    temporal["externalStorage"] = {
        "endpoint": "http://127.0.0.1:8333",
        "internalEndpoint": "http://seaweedfs:8333",
        "region": "us-east-1",
        "pathStyle": True,
        "bucket": "temporal-payloads",
        "driverName": "aws.s3driver",
        **writer,
        "readOnly": reader,
    }
    s3_config = {
        "identities": [
            {"name": "lab", "credentials": [{"accessKey": writer["accessKeyId"], "secretKey": writer["secretAccessKey"]}], "actions": ["Admin", "Read", "List", "Tagging", "Write"]},
            {"name": "lab-read-only", "credentials": [{"accessKey": reader["accessKeyId"], "secretKey": reader["secretAccessKey"]}], "actions": ["Read", "List"]},
        ]
    }
    write("seaweedfs/s3.json", json.dumps(s3_config, indent=2) + "\n")
    write("credentials.json", json.dumps(credentials, indent=2) + "\n")
    print("generate: added the S3 store of Temporal External Storage")


def ensure_codec():
    """The lab's payload codec (TSK-92): an AES-256-GCM key and the codec server's bearer token,
    added to an existing credentials.json without touching the rest."""
    path = os.path.join(OUT, "credentials.json")
    with open(path) as f:
        credentials = json.load(f)
    temporal = credentials.setdefault("temporal", {})
    if "codec" in temporal:
        return
    temporal["codec"] = {
        "endpoint": "http://127.0.0.1:8234",
        "internalEndpoint": "http://temporal-codec:8234",
        "authorization": "Bearer " + secrets.token_urlsafe(24),
        "key": base64.b64encode(os.urandom(32)).decode(),
        "taskQueue": "lab-encrypted",
    }
    write("credentials.json", json.dumps(credentials, indent=2) + "\n")
    print("generate: added the payload codec of Temporal")


def main(argv):
    force = "--force" in argv
    if all(os.path.exists(os.path.join(OUT, f)) for f in REQUIRED) and not force:
        ensure_s3()
        ensure_codec()
        print("generate: lab/.generated is already there (use --force for new credentials)")
        return 0
    ca_key, ca_cert = ca()
    write("tls/ca.pem", ca_cert.public_bytes(serialization.Encoding.PEM))
    for name, dns in [("nats", ["localhost", "nats"]), ("kafka", ["localhost", "kafka"])]:
        key, cert = leaf(ca_key, ca_cert, name, dns, ["127.0.0.1"])
        cert_pem = cert.public_bytes(serialization.Encoding.PEM)
        write(f"tls/{name}.pem", cert_pem + ca_cert.public_bytes(serialization.Encoding.PEM))
        write(f"tls/{name}-key.pem", pem_key(key))
        if name == "kafka":
            write("tls/kafka-keystore.pem", pem_key(key) + cert_pem + ca_cert.public_bytes(serialization.Encoding.PEM))

    nats_password = secrets.token_urlsafe(18)
    seed = nkeys.from_seed(nkeys.encode_seed(os.urandom(32), nkeys.PREFIX_BYTE_USER))
    nkey_public = seed.public_key.decode()
    nkey_seed = seed.seed.decode()
    write("nats.conf", NATS_CONF.format(user="lab", password=nats_password, nkey=nkey_public))
    write("nats/lab.nk", nkey_seed + "\n", 0o600)
    nats_token = secrets.token_urlsafe(18)
    write("nats-token.conf", NATS_TOKEN_CONF.format(token=nats_token))
    jwt_conf, creds = operator_mode()
    write("nats-jwt.conf", jwt_conf)
    write("nats/lab.creds", creds, 0o600)
    write("kafka/server.properties", KAFKA_PROPERTIES)

    passphrase = secrets.token_urlsafe(12)
    plain_private, plain_public = ssh_key()
    pass_private, pass_public = ssh_key(passphrase)
    write("ssh/lab_ed25519", plain_private, 0o600)
    write("ssh/lab_ed25519.pub", plain_public + b"\n")
    write("ssh/lab_ed25519_passphrase", pass_private, 0o600)
    write("ssh/lab_ed25519_passphrase.pub", pass_public + b"\n")
    write("ssh/authorized_keys", plain_public + b"\n" + pass_public + b"\n")
    ssh_password = secrets.token_urlsafe(12)
    write("ssh/labpw.password", ssh_password + "\n")

    credentials = {
        "nats": {
            "url": "nats://127.0.0.1:4222",
            "user": "lab",
            "password": nats_password,
            "nkeySeedFile": "nats/lab.nk",
            "nkeyPublic": nkey_public,
            "caFile": "tls/ca.pem",
            "tokenUrl": "nats://127.0.0.1:4223",
            "token": nats_token,
            "credsUrl": "nats://127.0.0.1:4224",
            "credsFile": "nats/lab.creds",
        },
        "kafka": {
            "plaintext": "127.0.0.1:9092",
            "ssl": "localhost:9093",
            "sasl": "127.0.0.1:9094",
            "scram": {"mechanism": "SCRAM-SHA-512", "user": "lab", "password": secrets.token_urlsafe(18)},
            "caFile": "tls/ca.pem",
        },
        "schemaRegistry": {"url": "http://127.0.0.1:8081"},
        "k8s": {"kubeconfigFile": "kubeconfig", "namespace": "lab"},
        "temporal": {"address": "127.0.0.1:7233", "namespaces": ["default", "lab"], "taskQueue": "lab"},
        "docker": {
            "host": "127.0.0.1",
            "port": 2222,
            "user": "lab",
            "keyFile": "ssh/lab_ed25519",
            "passphraseKeyFile": "ssh/lab_ed25519_passphrase",
            "passphrase": passphrase,
            "passwordUser": "labpw",
            "password": ssh_password,
            "noForwardUser": "nofwd",
        },
        "langgraph": {"url": "http://127.0.0.1:2024", "graph": "agent"},
    }
    write("credentials.json", json.dumps(credentials, indent=2) + "\n")
    ensure_s3()
    ensure_codec()
    print(f"generate: wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
