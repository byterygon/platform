//! Renders `api.ts`.
//!
//! The file is self-contained (no imports) and has three parts: identity constants, every type
//! ts-rs declares (sorted by name) plus the protocol's error union, and the procedure table. The
//! table is one value, `procedures`, nested by name segment (`procedures.query.execute`), whose
//! leaves carry the procedure's metadata and, at the type level only, its input, output and
//! error types. The runtime (`@byterygon/ambidex`) maps it to call signatures:
//! `createClient(procedures, transport).query.execute(input, opts)`.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use serde_json::{Value, json};

use super::manifest::duration_ms;
use super::{Model, Resolved};
use crate::frame::PROTOCOL_VERSION;
use crate::procedure::{Agent, ProcedureKind};
use security_types::Risk;

const HEADER: &str = "\
// Generated by rpc-gen from the Rust procedure registry (Ambidex spec §2). Do not edit:
// change the Rust declarations and run rpc-gen again. CI fails when this file is stale.
//
// 64-bit integers (u64, i64, usize) are `number`, exact only up to 2^53 (MAX_SAFE_INTEGER).
";

/// Names `api.ts` defines itself. A ts-rs declaration with one of them is refused
/// ([`CodegenError::ReservedName`](super::CodegenError::ReservedName)); `Code` and
/// `ApprovalRequiredDetails` are the engine's own declarations.
pub(crate) const RESERVED: &[&str] = &[
    "API",
    "API_VERSION",
    "PROTOCOL",
    "SCHEMA_HASH",
    "RpcError",
    "ProcedureKind",
    "Risk",
    "AgentExposure",
    "ProcedureDef",
    "Procedures",
    "Api",
    "procedures",
];

const PROTOCOL_TYPES: &str = "\
/**
 * An error a call fails with (spec §10). Narrow on `code`; `details` is the procedure's typed
 * domain error `D`. An `ApprovalRequired` error raised by the authorizer carries the approval id
 * instead, so its `details` are either; tell them apart with `\"approval_id\" in details`.
 */
export type RpcError<D = never> =
  | {
      code: \"ApprovalRequired\";
      message: string;
      details?: ApprovalRequiredDetails | D;
      retryable: boolean;
      correlation_id: string;
    }
  | {
      code: Exclude<Code, \"ApprovalRequired\">;
      message: string;
      details?: D;
      retryable: boolean;
      correlation_id: string;
    };
";

const PROCEDURE_DEF: &str = "\
/**
 * One procedure. The metadata is what the server registered; `__types` exists only at the type
 * level (it is never set) and carries the input, the output (one event for a subscription, the
 * final result for a stream) and the error type.
 */
export interface ProcedureDef<
  K extends ProcedureKind = ProcedureKind,
  I = unknown,
  O = unknown,
  D = unknown,
> {
  readonly name: string;
  readonly kind: K;
  readonly perm: string;
  readonly risk: Risk;
  readonly agent: AgentExposure;
  readonly deprecated: boolean;
  readonly timeoutDefaultMs: number;
  readonly timeoutMaxMs: number;
  readonly __types?: {
    readonly input: I;
    readonly output: O;
    readonly error: RpcError<D>;
  };
}
";

pub(crate) fn api_ts(model: &Model, schema_hash: &str) -> String {
    let mut out = String::from(HEADER);
    let api = &model.api;
    let _ = write!(
        out,
        "\n/** API name the client announces in Hello. */\nexport const API = {};\n\
         /** Version of the API this file was generated from. */\nexport const API_VERSION = {};\n\
         /** Frame protocol major. */\nexport const PROTOCOL = {PROTOCOL_VERSION};\n\
         /** Sent in Hello; the server refuses any other value with `VersionMismatch`. */\n\
         export const SCHEMA_HASH = {};\n",
        json!(api.name),
        json!(api.version),
        json!(schema_hash),
    );

    out.push_str("\n// ---- Types\n");
    for decl in model.decls.values() {
        out.push('\n');
        if let Some(docs) = &decl.docs {
            out.push_str(docs.trim_end());
            out.push('\n');
        }
        out.push_str("export ");
        out.push_str(decl.decl.trim_end());
        out.push('\n');
    }

    out.push_str("\n// ---- Errors\n\n");
    out.push_str(PROTOCOL_TYPES);

    out.push_str("\n// ---- Procedures\n\n");
    let _ = writeln!(
        out,
        "export type ProcedureKind = {};",
        literals(&[
            ProcedureKind::Query,
            ProcedureKind::Mutation,
            ProcedureKind::Subscription,
            ProcedureKind::Stream,
        ])
    );
    let _ = writeln!(
        out,
        "export type Risk = {};",
        literals(&[Risk::Read, Risk::Write, Risk::Destructive])
    );
    let _ = writeln!(
        out,
        "export type AgentExposure = {};\n",
        literals(&[Agent::Exposed, Agent::Hidden])
    );
    out.push_str(PROCEDURE_DEF);

    out.push_str("\n/** Every procedure by full name. */\nexport interface Procedures {\n");
    for p in &model.procedures {
        let _ = writeln!(
            out,
            "  readonly {}: ProcedureDef<{}, {}, {}, {}>;",
            json!(p.meta.name),
            json!(p.meta.kind),
            p.input_ts,
            p.output_ts,
            p.error_ts
        );
    }
    out.push_str("}\n");

    let tree = Tree::build(&model.procedures);
    out.push_str("\n/** The procedures nested by name segment, as the client exposes them. */\n");
    out.push_str("export interface Api ");
    tree.write_type(1, &mut out);
    out.push('\n');

    out.push_str("\n/** The procedure table to pass to the runtime's `createClient`. */\n");
    out.push_str("export const procedures: Api = ");
    tree.write_value(1, &mut out);
    out.push_str(";\n");
    out
}

fn literals<T: serde::Serialize>(values: &[T]) -> String {
    values
        .iter()
        .map(|v| json!(v).to_string())
        .collect::<Vec<_>>()
        .join(" | ")
}

/// A property name: bare when it is an identifier, quoted otherwise.
fn key(name: &str) -> String {
    let mut chars = name.chars();
    let ident = chars
        .next()
        .is_some_and(|c| c.is_ascii_alphabetic() || c == '_' || c == '$')
        && chars.all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '$');
    if ident {
        name.to_owned()
    } else {
        Value::String(name.to_owned()).to_string()
    }
}

/// A key in an object literal. `__proto__: v` (bare or quoted) would set the prototype instead of
/// defining a property, so it is written as a computed key.
fn value_key(name: &str) -> String {
    if name == "__proto__" {
        "[\"__proto__\"]".to_owned()
    } else {
        key(name)
    }
}

enum Tree<'a> {
    Leaf(&'a Resolved),
    Node(BTreeMap<&'a str, Tree<'a>>),
}

impl<'a> Tree<'a> {
    /// Namespace conflicts were rejected before rendering.
    fn build(procedures: &'a [Resolved]) -> Tree<'a> {
        let mut root = BTreeMap::new();
        for p in procedures {
            let segments: Vec<&str> = p.meta.name.split('.').collect();
            let (last, path) = segments.split_last().expect("names have segments");
            let mut node = &mut root;
            for segment in path {
                let child = node
                    .entry(*segment)
                    .or_insert_with(|| Tree::Node(BTreeMap::new()));
                let Tree::Node(children) = child else {
                    unreachable!("namespace conflicts are rejected")
                };
                node = children;
            }
            node.insert(*last, Tree::Leaf(p));
        }
        Tree::Node(root)
    }

    fn write_type(&self, depth: usize, out: &mut String) {
        match self {
            Tree::Leaf(p) => {
                let _ = write!(out, "Procedures[{}]", json!(p.meta.name));
            }
            Tree::Node(children) => {
                out.push_str("{\n");
                for (name, child) in children {
                    let _ = write!(out, "{}readonly {}: ", "  ".repeat(depth), key(name));
                    child.write_type(depth + 1, out);
                    out.push_str(";\n");
                }
                out.push_str(&"  ".repeat(depth - 1));
                out.push('}');
            }
        }
    }

    fn write_value(&self, depth: usize, out: &mut String) {
        let pad = "  ".repeat(depth);
        match self {
            Tree::Leaf(p) => {
                let m = &p.meta;
                out.push_str("{\n");
                let fields = [
                    ("name", json!(m.name)),
                    ("kind", json!(m.kind)),
                    ("perm", json!(m.perm.as_str())),
                    ("risk", json!(m.risk)),
                    ("agent", json!(m.agent)),
                    ("deprecated", json!(m.deprecated)),
                    ("timeoutDefaultMs", json!(duration_ms(m.timeout_default))),
                    ("timeoutMaxMs", json!(duration_ms(m.timeout_max))),
                ];
                for (name, value) in fields {
                    let _ = writeln!(out, "{pad}{name}: {value},");
                }
            }
            Tree::Node(children) => {
                out.push_str("{\n");
                for (name, child) in children {
                    let _ = write!(out, "{pad}{}: ", value_key(name));
                    child.write_value(depth + 1, out);
                    out.push_str(",\n");
                }
            }
        }
        out.push_str(&"  ".repeat(depth - 1));
        out.push('}');
    }
}
